import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const projectRoot = path.resolve(scriptDir, '..', '..')
const sourcePath = path.join(projectRoot, 'docs', 'v5p-h-token-catalog-zh.md')
const outputPath = path.join(projectRoot, 'client', 'src', 'generated', 'v5pHTokenCatalog.ts')
const rowPattern = /^\| (\d+) \| `(.*?)` \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$/

const rows = fs.readFileSync(sourcePath, 'utf8')
  .split(/\r?\n/)
  .map(line => rowPattern.exec(line))
  .filter(Boolean)
  .map(match => ({
    id: Number(match[1]),
    token: match[2].replaceAll('\\|', '|'),
    chineseName: match[3],
    explanation: match[4],
    editorVisibility: match[5],
    trainingEvidence: match[6],
    v5p40kSeen: match[6].startsWith('是'),
  }))

if (rows.length !== 367 || rows.some((row, index) => row.id !== index)) {
  throw new Error(`Expected dense runtime IDs 0..366, received ${rows.length} rows`)
}

const output = `// Generated by scripts/generate-v5p-h-token-catalog.mjs from docs/v5p-h-token-catalog-zh.md.\n`+
`// Do not edit this file by hand.\n\n`+
`export interface V5PHTokenCatalogEntry {\n`+
`  id: number\n`+
`  token: string\n`+
`  chineseName: string\n`+
`  explanation: string\n`+
`  editorVisibility: string\n`+
`  trainingEvidence: string\n`+
`  v5p40kSeen: boolean\n`+
`}\n\n`+
`export const V5P_H_TOKEN_CATALOG: readonly V5PHTokenCatalogEntry[] = ${JSON.stringify(rows, null, 2)}\n`+
`export const V5P_H_TOKEN_BY_ID = new Map(V5P_H_TOKEN_CATALOG.map(entry => [entry.id, entry]))\n`

fs.mkdirSync(path.dirname(outputPath), { recursive: true })
fs.writeFileSync(outputPath, output, 'utf8')
console.log(`Wrote ${rows.length} H tokens to ${outputPath}`)
